`timescale 1ns / 1ns
//============================================================
// Тестбенч: main_1_tb
//
// Назначение:
//   Проверка работы верхнего модуля main_1.
//
// Проверяемые функции:
//
//   1. Сброс таймера.
//   2. Загрузка начального значения.
//   3. Запуск обратного отсчета.
//   4. Остановка счета.
//   5. Возобновление счета.
//   6. Формирование сигнала zero.
//
// Для ускорения моделирования:
//   CLK_FREQ уменьшен до 10.
//============================================================

module main_1_tb;
    //--------------------------------------------------------
    // Параметры теста
    //--------------------------------------------------------

    parameter CLK_FREQ = 10;

    //--------------------------------------------------------
    // Сигналы тестового окружения
    //--------------------------------------------------------
    reg clk;
    reg rst;
    reg load;
    reg enable;

    //--------------------------------------------------------
    // Начальное время
    // Устанавливаем:
    //        01:05
    //--------------------------------------------------------

    reg [3:0] load_sec_u;
    reg [3:0] load_sec_t;

    reg [3:0] load_min_u;
    reg [3:0] load_min_t;

    //--------------------------------------------------------
    // Выходы DUT
    //--------------------------------------------------------

    wire [3:0] sec_u;
    wire [3:0] sec_t;

    wire [3:0] min_u;
    wire [3:0] min_t;

    wire zero;

    //--------------------------------------------------------
    // Генерация тактового сигнала
    // Период 10 нс
    // Частота 100 MHz
    //--------------------------------------------------------
    always #5 clk = ~clk;

    //--------------------------------------------------------
    // Экземпляр проверяемого модуля
    //--------------------------------------------------------
    main_1_initial
    #(
        .CLK_FREQ(CLK_FREQ)
    )
    DUT
    (
        .clk(clk),
        .rst(rst),

        .load(load),
        .enable(enable),


        .load_sec_u(load_sec_u),
        .load_sec_t(load_sec_t),

        .load_min_u(load_min_u),
        .load_min_t(load_min_t),


        .sec_u(sec_u),
        .sec_t(sec_t),

        .min_u(min_u),
        .min_t(min_t),

        .zero(zero)
    );

    //--------------------------------------------------------
    // Основной сценарий теста
    //--------------------------------------------------------
    initial begin

        //----------------------------------------------------
        // Начальные значения
        //----------------------------------------------------

        clk = 0;

        rst = 1;

        load = 0;

        enable = 0;


        load_sec_u = 5;
        load_sec_t = 0;

        load_min_u = 1;
        load_min_t = 0;

        //----------------------------------------------------
        // Сброс
        //----------------------------------------------------

        #30;
        rst = 0;

        //----------------------------------------------------
        // Загрузка времени 01:05
        //----------------------------------------------------

        #20;
        load = 1;

        #10;
        load = 0;

        //----------------------------------------------------
        // Проверка состояния
        //----------------------------------------------------
        #20;
        $display("--------------------------------");
        $display("Loaded time:");
        $display("%d%d:%d%d",
                 min_t,
                 min_u,
                 sec_t,
                 sec_u);
        $display("--------------------------------");

        //----------------------------------------------------
        // Запуск таймера
        //----------------------------------------------------
        enable = 1;

        //----------------------------------------------------
        // Работа таймера
        // Ожидаем:
        // 01:05
        // 01:04
        // 01:03
        // ...
        //
        //----------------------------------------------------
        #250;

        //----------------------------------------------------
        // Остановка счета
        //----------------------------------------------------
        enable = 0;

        #50;
        $display("--------------------------------");
        $display("Paused time:");
        $display("%d%d:%d%d",
                 min_t,
                 min_u,
                 sec_t,
                 sec_u);
        $display("--------------------------------");

        //----------------------------------------------------
        // Возобновление
        //----------------------------------------------------
        enable = 1;

        #300;
        //----------------------------------------------------
        // Завершение моделирования
        //----------------------------------------------------
        $display("--------------------------------");
        $display("Final time:");
        $display("%d%d:%d%d",
                 min_t,
                 min_u,
                 sec_t,
                 sec_u);

        $display("ZERO = %b", zero);

        $display("--------------------------------");

        $finish;
    end
endmodule
