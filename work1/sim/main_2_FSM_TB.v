`timescale 1ns / 1ns
//============================================================
// Тестбенч: main_2_FSM_tb
//
// Назначение:
//   Проверка работы таймера с управляющим FSM.
//
// Проверяем:
//
//   1. Сброс.
//   2. Загрузка времени.
//   3. Запуск.
//   4. Пауза.
//   5. Продолжение счета.
//   6. Завершение отсчета.
//
// Для моделирования:
//
//   CLK_FREQ = 10
//
// Это позволяет получить секундный импульс
// через 10 тактов.
//
//============================================================


`timescale 1ns/1ps


module main_2_FSM_tb;


    //--------------------------------------------------------
    // Параметры симуляции
    //--------------------------------------------------------

    parameter CLK_FREQ = 10;



    //--------------------------------------------------------
    // Тактовый сигнал
    //--------------------------------------------------------

    reg clk;



    //--------------------------------------------------------
    // Управляющие сигналы
    //--------------------------------------------------------

    reg reset;

    reg load;

    reg start;

    reg pause;



    //--------------------------------------------------------
    // Начальное время
    //
    // Устанавливаем:
    //
    //       00:05
    //
    //--------------------------------------------------------

    reg [3:0] load_sec_u;
    reg [3:0] load_sec_t;

    reg [3:0] load_min_u;
    reg [3:0] load_min_t;



    //--------------------------------------------------------
    // Выходы DUT
    //--------------------------------------------------------

    wire [3:0] sec_u;
    wire [3:0] sec_t;

    wire [3:0] min_u;
    wire [3:0] min_t;


    wire finish;



    //--------------------------------------------------------
    // Генератор тактового сигнала
    //
    // Период 10 нс
    //
    //--------------------------------------------------------

    always #5 clk = ~clk;



    //--------------------------------------------------------
    // Экземпляр проверяемого модуля
    //--------------------------------------------------------

    main_2_FSM
    #(
        .CLK_FREQ(CLK_FREQ)
    )
    DUT
    (

        .clk(clk),

        .reset(reset),


        .load(load),

        .start(start),

        .pause(pause),



        .load_sec_u(load_sec_u),

        .load_sec_t(load_sec_t),

        .load_min_u(load_min_u),

        .load_min_t(load_min_t),



        .sec_u(sec_u),

        .sec_t(sec_t),

        .min_u(min_u),

        .min_t(min_t),



        .finish(finish)

    );



    //--------------------------------------------------------
    // Вывод состояния таймера
    //--------------------------------------------------------

    initial
    begin

        $monitor(
        "time=%0t  timer=%d%d:%d%d finish=%b",
        $time,
        min_t,
        min_u,
        sec_t,
        sec_u,
        finish
        );

    end



    //--------------------------------------------------------
    // Основной тест
    //--------------------------------------------------------

    initial
    begin


        //----------------------------------------------------
        // Начальные значения
        //----------------------------------------------------

        clk = 0;

        reset = 1;

        load = 0;

        start = 0;

        pause = 0;



        load_min_t = 0;
        load_min_u = 0;

        load_sec_t = 0;
        load_sec_u = 5;



        //----------------------------------------------------
        // Сброс
        //----------------------------------------------------

        #30;

        reset = 0;



        //----------------------------------------------------
        // Загрузка времени 00:05
        //----------------------------------------------------

        #20;

        load = 1;


        #20;

        load = 0;



        //----------------------------------------------------
        // Запуск таймера
        //----------------------------------------------------

        #20;

        start = 1;


        #10;

        start = 0;



        //----------------------------------------------------
        // Работа таймера
        //
        // Ожидаем:
        //
        // 00:05
        // 00:04
        // 00:03
        // ...
        //
        //----------------------------------------------------

        #40;



        //----------------------------------------------------
        // Проверка паузы
        //----------------------------------------------------

        pause = 1;


        #10;

        pause = 0;


        // Таймер должен остановиться

        #40;



        //----------------------------------------------------
        // Продолжение счета
        //----------------------------------------------------

        pause = 1;


        #10;

        pause = 0;



        //----------------------------------------------------
        // Ожидание окончания
        //----------------------------------------------------

        #120;



        //----------------------------------------------------
        // Проверка reset из FINISH
        //----------------------------------------------------

        reset = 1;


        #20;


        reset = 0;



        //----------------------------------------------------
        // Завершение моделирования
        //----------------------------------------------------

        #50;


        $finish;


    end



endmodule
