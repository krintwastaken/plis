`timescale 1ns / 1ns
//============================================================
// Модуль: main_basys3_SSI
// Назначение:
//   Верхний уровень таймера для платы Basys3.
//
// Ввод начального значения: 
//   SW[15:12] - десятки минут;
//   SW[11:8]  - единицы минут;
//   SW[7:4]   - десятки секунд;
//   SW[3:0]   - единицы секунд.
//
// Управление:
//   btnc (центральная) - reset, сброс
//   btnd (нижняя) - load, загрузка начального значения
//   btnl (левая) - start, начало счета 
//   btnu (верхняя) - pause, останов/Продолжение счета

//
// Индикация:
//   четыре семисегментных индикатора;
//   формат MM:SS без отображения двоеточия.
//
//============================================================

module basys3_SSI_top #(
    parameter integer CLK_FREQ    = 100_000_000,
    parameter integer DEBOUNCE_MS = 20,
    parameter integer SCAN_FREQ_HZ = 1000
)(
    //--------------------------------------------------------
    // Тактовый сигнал платы
    //--------------------------------------------------------
    input wire CLK100MHZ,

    //--------------------------------------------------------
    // Кнопки Basys3
    //--------------------------------------------------------
    input wire btnC,
    input wire btnU,
    input wire btnD,
    input wire btnL,

    //--------------------------------------------------------
    // Переключатели
    //--------------------------------------------------------
    input wire [15:0] SW,

    //--------------------------------------------------------
    // Семисегментный индикатор
    //--------------------------------------------------------
    output wire [6:0] seg,
    output wire       dp,
    output wire [3:0] an
);

    //--------------------------------------------------------
    // Системные сигналы
    //--------------------------------------------------------
    wire clk_sys;
    wire reset_sync;

    //--------------------------------------------------------
    // Очищенные импульсы кнопок
    //--------------------------------------------------------
    wire load_pulse;
    wire start_pulse;
    wire pause_pulse;

    //--------------------------------------------------------
    // Устойчивые уровни кнопок
    // В этой версии верхнего уровня не используются,
    // но подключены для полноты интерфейса дебаунсеров.
    //--------------------------------------------------------
    wire load_level;
    wire start_level;
    wire pause_level;

    //--------------------------------------------------------
    // Текущее значение таймера
    //--------------------------------------------------------
    wire [3:0] sec_u;
    wire [3:0] sec_t;
    wire [3:0] min_u;
    wire [3:0] min_t;

    //--------------------------------------------------------
    // Признак окончания счета
    //--------------------------------------------------------
    wire finish;

    //--------------------------------------------------------
    // Общая восьмиразрядная шина индикатора:
    // bit 7   - decimal point;
    // bits 6:0 - segments G...A.
    //--------------------------------------------------------
    wire [7:0] sseg_bus;

    //--------------------------------------------------------
    // Формирование системного тактового сигнала и синхронного сброса
    //--------------------------------------------------------
    clock_manager u_clock_manager (
        .clk100     (CLK100MHZ),
        .reset      (btnC),
        .clk_sys    (clk_sys),
        .reset_sync (reset_sync)
    );

//    clk_wiz_0 main_clock (
//        .clk_in1 (CLK100MHZ),
//        .locked  (clk_locked),
//        .clk_out1(clk_200),
//    );


    //--------------------------------------------------------
    // Фильтр кнопки LOAD
    //--------------------------------------------------------
    button_debouncer #(
        .CLK_FREQ    (CLK_FREQ),
        .DEBOUNCE_MS (DEBOUNCE_MS)
    )
    u_debouncer_load (
        .clk          (clk_sys),
        .rst          (reset_sync),
        .button_in    (btnU),
        .button_level (load_level),
        .button_pulse (load_pulse)
    );

    //--------------------------------------------------------
    // Фильтр кнопки START
    //--------------------------------------------------------
    button_debouncer #(
        .CLK_FREQ    (CLK_FREQ),
        .DEBOUNCE_MS (DEBOUNCE_MS)
    )
    u_debouncer_start (
        .clk          (clk_sys),
        .rst          (reset_sync),
        .button_in    (btnD),
        .button_level (start_level),
        .button_pulse (start_pulse)
    );

    //--------------------------------------------------------
    // Фильтр кнопки PAUSE
    //--------------------------------------------------------
    button_debouncer #(
        .CLK_FREQ    (CLK_FREQ),
        .DEBOUNCE_MS (DEBOUNCE_MS)
    )
    u_debouncer_pause (
        .clk          (clk_sys),
        .rst          (reset_sync),
        .button_in    (btnL),
        .button_level (pause_level),
        .button_pulse (pause_pulse)
    );

    //--------------------------------------------------------
    // Ядро таймера
    //--------------------------------------------------------
    main_2_FSM #(
        .CLK_FREQ (CLK_FREQ)
    )
    u_timer (
        .clk        (clk_sys),
        .reset      (reset_sync),

        .load       (load_pulse),
        .start      (start_pulse),
        .pause      (pause_pulse),

        .load_sec_u (SW[3:0]),
        .load_sec_t (SW[7:4]),
        .load_min_u (SW[11:8]),
        .load_min_t (SW[15:12]),

        .sec_u      (sec_u),
        .sec_t      (sec_t),
        .min_u      (min_u),
        .min_t      (min_t),

        .finish     (finish)
    );

    //--------------------------------------------------------
    // Контроллер семисегментного индикатора
    // digit0 соответствует AN0 - крайнему правому разряду.
    // digit3 соответствует AN3 - крайнему левому разряду.
    //--------------------------------------------------------

    display_controller #(
        .CLK_FREQ     (CLK_FREQ),
        .SCAN_FREQ_HZ (SCAN_FREQ_HZ)) 
        u_display_controller (

        .clk            (clk_sys),
        .rst            (reset_sync),

        .digit0         (sec_u),
        .digit1         (sec_t),
        .digit2         (min_u),
        .digit3         (min_t),

        .blink          (1'b0),
        .blink_enable   (1'b0),
        .selected_digit (2'b00),

        .seg            (sseg_bus),
        .an             (an)
    );

    //--------------------------------------------------------
    // Разделение общей шины сегментов на порты Basys3
    //--------------------------------------------------------
    assign dp  = sseg_bus[7];
    assign seg = sseg_bus[6:0];

endmodule


